/// SHA-512 incrémental (un installateur de plusieurs dizaines de Mo n'est pas chargé d'un coup).
#[derive(Clone)]
pub struct Sha512 {
    h: [u64; 8],
    buffer: Vec<u8>,
    length: u128,
}

impl Default for Sha512 {
    fn default() -> Self {
        Self::new()
    }
}

impl Sha512 {
    pub fn new() -> Self {
        Sha512 {
            h: [
                0x6a09e667f3bcc908, 0xbb67ae8584caa73b, 0x3c6ef372fe94f82b, 0xa54ff53a5f1d36f1, 0x510e527fade682d1, 0x9b05688c2b3e6c1f,
                0x1f83d9abfb41bd6b, 0x5be0cd19137e2179,
            ],
            buffer: Vec::with_capacity(128),
            length: 0,
        }
    }

    pub fn update(&mut self, mut data: &[u8]) {
        self.length += data.len() as u128;
        if !self.buffer.is_empty() {
            let take = (128 - self.buffer.len()).min(data.len());
            self.buffer.extend_from_slice(&data[..take]);
            data = &data[take..];
            if self.buffer.len() == 128 {
                let block = std::mem::take(&mut self.buffer);
                self.compress(&block);
                self.buffer = Vec::with_capacity(128);
            }
        }
        let mut chunks = data.chunks_exact(128);
        for block in &mut chunks {
            self.compress(block);
        }
        self.buffer.extend_from_slice(chunks.remainder());
    }

    fn compress(&mut self, block: &[u8]) {
        let mut w = [0u64; 80];
        for i in 0..16 {
            let mut b = [0u8; 8];
            b.copy_from_slice(&block[8 * i..8 * i + 8]);
            w[i] = u64::from_be_bytes(b);
        }
        for i in 16..80 {
            let s0 = w[i - 15].rotate_right(1) ^ w[i - 15].rotate_right(8) ^ (w[i - 15] >> 7);
            let s1 = w[i - 2].rotate_right(19) ^ w[i - 2].rotate_right(61) ^ (w[i - 2] >> 6);
            w[i] = w[i - 16].wrapping_add(s0).wrapping_add(w[i - 7]).wrapping_add(s1);
        }
        let mut v = self.h;
        for i in 0..80 {
            let [a, b, c, d, e, f, g, hh] = v;
            let s1 = e.rotate_right(14) ^ e.rotate_right(18) ^ e.rotate_right(41);
            let ch = (e & f) ^ (!e & g);
            let t1 = hh.wrapping_add(s1).wrapping_add(ch).wrapping_add(K512[i]).wrapping_add(w[i]);
            let s0 = a.rotate_right(28) ^ a.rotate_right(34) ^ a.rotate_right(39);
            let maj = (a & b) ^ (a & c) ^ (b & c);
            let t2 = s0.wrapping_add(maj);
            v = [t1.wrapping_add(t2), a, b, c, d.wrapping_add(t1), e, f, g];
        }
        for (x, y) in self.h.iter_mut().zip(v) {
            *x = x.wrapping_add(y);
        }
    }

    pub fn finish(mut self) -> [u8; 64] {
        let bit_len = self.length * 8;
        let mut tail = std::mem::take(&mut self.buffer);
        tail.push(0x80);
        while tail.len() % 128 != 112 {
            tail.push(0);
        }
        tail.extend_from_slice(&bit_len.to_be_bytes());
        for block in tail.chunks(128) {
            self.compress(block);
        }
        let mut out = [0u8; 64];
        for (i, v) in self.h.iter().enumerate() {
            out[8 * i..8 * i + 8].copy_from_slice(&v.to_be_bytes());
        }
        out
    }
}

pub fn sha512(data: &[u8]) -> [u8; 64] {
    let mut h = Sha512::new();
    h.update(data);
    h.finish()
}

/// Message complété (bit 1, zéros, longueur en bits sur `len_bytes` octets).
fn padded(data: &[u8], block: usize, len_bytes: usize) -> Vec<u8> {
    let mut out = data.to_vec();
    out.push(0x80);
    while out.len() % block != block - len_bytes {
        out.push(0);
    }
    let bits = (data.len() as u64).wrapping_mul(8);
    out.extend_from_slice(&bits.to_be_bytes());
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::util::encoding::hex_encode;

    #[test]
    fn sha1_vectors() {
        assert_eq!(hex_encode(&sha1(b"")), "da39a3ee5e6b4b0d3255bfef95601890afd80709");
        assert_eq!(hex_encode(&sha1(b"abc")), "a9993e364706816aba3e25717850c26c9cd0d89d");
        assert_eq!(
            hex_encode(&sha1(b"abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq")),
            "84983e441c3bd26ebaae4aa1f95129e5e54670f1"
        );
    }

    #[test]
    fn sha256_vectors() {
        assert_eq!(hex_encode(&sha256(b"")), "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855");
        assert_eq!(hex_encode(&sha256(b"abc")), "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad");
        let million_a = vec![b'a'; 1_000_000];
        assert_eq!(hex_encode(&sha256(&million_a)), "cdc76e5c9914fb9281a1c7e284d73e67f1809a48a497200e046d39ccc7112cd0");
    }

    #[test]
    fn sha512_vectors_and_streaming() {
        assert_eq!(
            hex_encode(&sha512(b"abc")),
            "ddaf35a193617abacc417349ae20413112e6fa4e89a97ea20a9eeee64b55d39a2192992a274fc1a836ba3c23a3feebbd454d4423643ce80e2a9ac94fa54ca49f"
        );
        assert_eq!(
            hex_encode(&sha512(b"")),
            "cf83e1357eefb8bdf1542850d66d8007d620e4050b5715dc83f4a921d36ce9ce47d0d13c5d85f2b0ff8318d2877eec2f63b931bd47417a81a538327af927da3e"
        );
        let data: Vec<u8> = (0..1000u32).map(|i| (i * 7 % 251) as u8).collect();
        let mut s = Sha512::new();
        for part in data.chunks(37) {
            s.update(part);
        }
        assert_eq!(s.finish(), sha512(&data));
    }
}
